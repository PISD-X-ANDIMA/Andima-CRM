#!/usr/bin/env node
/**
 * Migrasi tabel A2 dari Supabase ke Neon.
 *
 * Pemakaian:
 *   npm i -D pg
 *   node scripts/migrate-a2-neon.mjs                 # schema + data + verifikasi
 *   node scripts/migrate-a2-neon.mjs --verify-only   # cek saja, tidak menulis
 *   node scripts/migrate-a2-neon.mjs --reset         # drop lalu tulis ulang (window cutover)
 *   node scripts/migrate-a2-neon.mjs --include-worksheets
 *
 * Env (dibaca dari .env.local atau environment):
 *   SUPABASE_DB_URL    connection string Supabase (Settings > Database > Connection string)
 *   NEON_DATABASE_URL  connection string Neon unpooled (bukan host -pooler)
 *
 * Yang dibuat di Neon: kolom, PK, CHECK, index, dan FK yang menunjuk sesama tabel a2_.
 * Yang sengaja TIDAK dibuat: FK ke tabel kelompok lain (a1_/a3_/b2_/d3_/corp_jobs) dan RLS.
 *
 * Script memuat satu tabel ke memori sekaligus. Aman untuk ukuran A2 (puluhan ribu baris).
 */
import fs from 'node:fs';
import path from 'node:path';
import pg from 'pg';

// Timestamp dikembalikan sebagai string apa adanya supaya presisi mikrodetik tidak hilang lewat Date JS.
for (const oid of [1082, 1114, 1184]) pg.types.setTypeParser(oid, (v) => v);

function loadEnvLocal() {
  const file = path.join(process.cwd(), '.env.local');
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m || process.env[m[1]] !== undefined) continue;
    process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}

const BASE_TABLES = ['a2_record_conversations', 'a2_conversation_alerts', 'a2_field_task_notes'];
const OPTIONAL_TABLES = ['a2_worksheets'];

const args = new Set(process.argv.slice(2));
const opts = {
  reset: args.has('--reset'),
  verifyOnly: args.has('--verify-only'),
  includeWorksheets: args.has('--include-worksheets'),
};

const q = (id) => `"${String(id).replace(/"/g, '""')}"`;

function client(url) {
  // shortcut: verifikasi sertifikat dimatikan untuk script migrasi sekali-jalan.
  // Set ssl.rejectUnauthorized=true bila environment punya chain CA yang lengkap.
  return new pg.Client({ connectionString: url, ssl: { rejectUnauthorized: false } });
}

async function tableExists(c, table) {
  const { rows } = await c.query('SELECT to_regclass($1) AS t', [`public.${table}`]);
  return rows[0].t !== null;
}

async function columns(c, table) {
  const { rows } = await c.query(
    `SELECT a.attname AS name,
            format_type(a.atttypid, a.atttypmod) AS type,
            a.attnotnull AS notnull,
            a.attidentity AS identity,
            a.attgenerated AS generated,
            pg_get_expr(d.adbin, d.adrelid) AS default_expr
     FROM pg_attribute a
     LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
     WHERE a.attrelid = $1::regclass AND a.attnum > 0 AND NOT a.attisdropped
     ORDER BY a.attnum`,
    [`public.${table}`]
  );
  return rows;
}

async function primaryKey(c, table) {
  const { rows } = await c.query(
    `SELECT a.attname AS name
     FROM pg_index i
     JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
     WHERE i.indrelid = $1::regclass AND i.indisprimary
     ORDER BY array_position(i.indkey::int2[], a.attnum::int2)`,
    [`public.${table}`]
  );
  return rows.map((r) => r.name);
}

async function checkConstraints(c, table) {
  const { rows } = await c.query(
    `SELECT conname, pg_get_constraintdef(oid) AS def
     FROM pg_constraint
     WHERE conrelid = $1::regclass AND contype = 'c'`,
    [`public.${table}`]
  );
  return rows;
}

async function internalForeignKeys(c, table) {
  const { rows } = await c.query(
    `SELECT conname, pg_get_constraintdef(oid) AS def
     FROM pg_constraint
     WHERE conrelid = $1::regclass AND contype = 'f'
       AND pg_get_constraintdef(oid) ~ 'REFERENCES\\s+(public\\.)?a2_'`,
    [`public.${table}`]
  );
  return rows;
}

async function indexes(c, table) {
  const { rows } = await c.query(
    `SELECT indexname, indexdef
     FROM pg_indexes
     WHERE schemaname = 'public' AND tablename = $1
       AND indexname NOT IN (
         SELECT conname FROM pg_constraint WHERE conrelid = $2::regclass
       )`,
    [table, `public.${table}`]
  );
  return rows;
}

function columnDefinition(col) {
  let def = `${q(col.name)} ${col.type}`;
  if (col.generated === 's') return `${def} GENERATED ALWAYS AS (${col.default_expr}) STORED`;
  if (col.identity === 'a') def += ' GENERATED ALWAYS AS IDENTITY';
  else if (col.identity === 'd') def += ' GENERATED BY DEFAULT AS IDENTITY';
  else if (col.default_expr) def += ` DEFAULT ${col.default_expr}`;
  if (col.notnull) def += ' NOT NULL';
  return def;
}

async function createTable(src, dest, table) {
  const cols = await columns(src, table);
  const pk = await primaryKey(src, table);
  const checks = await checkConstraints(src, table);
  const fks = await internalForeignKeys(src, table);
  const idx = await indexes(src, table);

  const parts = cols.map(columnDefinition);
  if (pk.length) parts.push(`PRIMARY KEY (${pk.map(q).join(', ')})`);
  await dest.query(`CREATE TABLE public.${q(table)} (\n  ${parts.join(',\n  ')}\n)`);

  for (const ck of checks) {
    await dest.query(`ALTER TABLE public.${q(table)} ADD CONSTRAINT ${q(ck.conname)} ${ck.def}`);
  }
  for (const fk of fks) {
    await dest.query(`ALTER TABLE public.${q(table)} ADD CONSTRAINT ${q(fk.conname)} ${fk.def}`);
  }
  for (const ix of idx) {
    const ddl = ix.indexdef.replace(/^CREATE (UNIQUE )?INDEX /, (m, unique) => `CREATE ${unique || ''}INDEX IF NOT EXISTS `);
    await dest.query(ddl);
  }

  if (table === 'a2_conversation_alerts') {
    const statusCheck = checks.find((ck) => /status/i.test(ck.def));
    if (statusCheck && !statusCheck.def.includes('In Progress')) {
      console.warn('  WARN CHECK status belum mengizinkan \'In Progress\' — update manual setelah migrasi.');
    }
  }

  return cols;
}

async function copyRows(src, dest, table, cols) {
  const names = cols.filter((c) => c.generated !== 's').map((c) => c.name);
  const { rows } = await src.query(`SELECT ${names.map(q).join(', ')} FROM public.${q(table)}`);
  if (rows.length === 0) return 0;

  const CHUNK = 500;
  for (let i = 0; i < rows.length; i += CHUNK) {
    const params = [];
    const tuples = rows.slice(i, i + CHUNK).map((row) => {
      const placeholders = names.map((name) => {
        params.push(row[name]);
        return `$${params.length}`;
      });
      return `(${placeholders.join(', ')})`;
    });
    await dest.query(
      `INSERT INTO public.${q(table)} (${names.map(q).join(', ')}) VALUES ${tuples.join(', ')}`,
      params
    );
  }
  return rows.length;
}

async function countRows(c, table) {
  const { rows } = await c.query(`SELECT count(*)::int AS n FROM public.${q(table)}`);
  return rows[0].n;
}

async function verifyCounts(src, dest, tables) {
  let ok = true;
  for (const table of tables) {
    const [s, d] = await Promise.all([countRows(src, table), countRows(dest, table)]);
    const pass = s === d;
    if (!pass) ok = false;
    console.log(`  ${pass ? 'OK  ' : 'FAIL'} ${table}: supabase=${s} neon=${d}`);
  }
  return ok;
}

async function verifyColumns(src, dest, tables) {
  let ok = true;
  for (const table of tables) {
    const [sc, dc] = await Promise.all([columns(src, table), columns(dest, table)]);
    const a = sc.map((c) => `${c.name} ${c.type}`).join(' | ');
    const b = dc.map((c) => `${c.name} ${c.type}`).join(' | ');
    if (a === b) {
      console.log(`  OK   kolom ${table}`);
    } else {
      ok = false;
      console.log(`  FAIL kolom ${table}\n    supabase: ${a}\n    neon    : ${b}`);
    }
  }
  return ok;
}

async function main() {
  loadEnvLocal();

  const srcUrl = process.env.SUPABASE_DB_URL;
  const destUrl = process.env.NEON_DATABASE_URL;
  if (!srcUrl || !destUrl) {
    console.error('Set SUPABASE_DB_URL dan NEON_DATABASE_URL (di .env.local atau environment).');
    process.exit(1);
  }

  const src = client(srcUrl);
  const dest = client(destUrl);
  await src.connect();
  await dest.connect();

  try {
    const tables = [...BASE_TABLES];
    for (const table of OPTIONAL_TABLES) {
      if (!(await tableExists(src, table))) continue;
      if (opts.includeWorksheets) tables.push(table);
      else console.log(`WARN ${table} ada di Supabase tapi dilewati (pakai --include-worksheets untuk ikut).`);
    }

    if (opts.verifyOnly) {
      console.log('Verifikasi:');
      const countsOk = await verifyCounts(src, dest, tables);
      const colsOk = await verifyColumns(src, dest, tables);
      process.exitCode = countsOk && colsOk ? 0 : 1;
      return;
    }

    for (const table of tables) {
      if (!(await tableExists(src, table))) {
        console.log(`SKIP ${table}: tidak ada di Supabase.`);
        continue;
      }
      const exists = await tableExists(dest, table);
      if (exists && !opts.reset) {
        console.log(`SKIP ${table}: sudah ada di Neon (pakai --reset untuk tulis ulang).`);
        continue;
      }
      if (exists && opts.reset) {
        await dest.query(`DROP TABLE IF EXISTS public.${q(table)} CASCADE`);
        console.log(`DROP ${table} (Neon).`);
      }
      const cols = await createTable(src, dest, table);
      const copied = await copyRows(src, dest, table, cols);
      console.log(`COPY ${table}: ${copied} baris.`);
    }

    console.log('Verifikasi:');
    const countsOk = await verifyCounts(src, dest, tables);
    const colsOk = await verifyColumns(src, dest, tables);
    process.exitCode = countsOk && colsOk ? 0 : 1;
  } finally {
    await src.end();
    await dest.end();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
