// Search function specialized for Indonesian cities, kabupaten, ports & industrial areas
export function searchIndonesiaCities(
  query: string,
  limit: number = 35
): string[] {
  const q = query.trim().toLowerCase();

  // If query is empty, return popular default origins
  if (!q) {
    return DEFAULT_INDONESIA_ORIGINS;
  }

  const results: string[] = [];
  const seen = new Set<string>();

  // 1. Exact or prefix match on city name, port, or code
  for (const item of ALL_INDONESIA_LOCATIONS) {
    const cityLow = item.city.toLowerCase();
    const provLow = item.province.toLowerCase();
    const codeLow = item.code?.toLowerCase() || "";

    const isDirectMatch =
      cityLow.startsWith(q) ||
      provLow.startsWith(q) ||
      codeLow === q ||
      item.keywords.some((k) => k.startsWith(q));

    if (isDirectMatch && !seen.has(item.display)) {
      seen.add(item.display);
      results.push(item.display);
      if (results.length >= limit) return results;
    }
  }

  // 2. Substring / includes match
  for (const item of ALL_INDONESIA_LOCATIONS) {
    if (seen.has(item.display)) continue;

    const cityLow = item.city.toLowerCase();
    const provLow = item.province.toLowerCase();
    const dispLow = item.display.toLowerCase();

    const isMatch =
      dispLow.includes(q) ||
      cityLow.includes(q) ||
      provLow.includes(q) ||
      item.keywords.some((k) => k.includes(q));

    if (isMatch) {
      seen.add(item.display);
      results.push(item.display);
      if (results.length >= limit) return results;
    }
  }

  return results;
}

