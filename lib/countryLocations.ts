// Fast search function returning matching display names
export function searchCountryLocations(
  query: string,
  isOrigin = false,
  limit = 40
): string[] {
  // If searching Origin, prioritize Indonesian cities, regencies, ports & industrial hubs
  if (isOrigin) {
    const indoResults = searchIndonesiaCities(query, limit);
    if (indoResults.length > 0) {
      return indoResults;
    }
  }

  const q = query.trim().toLowerCase();

  // If query is empty, return popular default options
  if (!q) {
    return isOrigin ? DEFAULT_INDONESIA_ORIGINS : DEFAULT_DESTINATION_PORTS;
  }

  const results: string[] = [];
  const seen = new Set<string>();

  // 1. Exact or prefix matches on country / port
  for (const item of ALL_WORLD_COUNTRIES_AND_PORTS) {
    const cId = item.countryId.toLowerCase();
    const cEn = item.countryEn.toLowerCase();
    const city = item.cityOrPort?.toLowerCase() || "";
    const code = item.code?.toLowerCase() || "";

    const countryMatches =
      cId.startsWith(q) ||
      cEn.startsWith(q) ||
      item.keywords.some((k) => k.startsWith(q));

    // If matching by country, prioritize the country name itself first
    if (countryMatches) {
      const countryTitle =
        item.countryId.toLowerCase() === item.countryEn.toLowerCase()
          ? item.countryId
          : `${item.countryId} (${item.countryEn})`;
      if (!seen.has(countryTitle)) {
        seen.add(countryTitle);
        results.push(countryTitle);
        if (results.length >= limit) return results;
      }
    }

    const isMatch =
      countryMatches ||
      city.startsWith(q) ||
      code === q;

    if (isMatch && !seen.has(item.display)) {
      seen.add(item.display);
      results.push(item.display);
      if (results.length >= limit) return results;
    }
  }

  // 2. Substring / includes matches
  for (const item of ALL_WORLD_COUNTRIES_AND_PORTS) {
    const cId = item.countryId.toLowerCase();
    const cEn = item.countryEn.toLowerCase();
    const city = item.cityOrPort?.toLowerCase() || "";
    const display = item.display.toLowerCase();

    const countryMatches =
      cId.includes(q) ||
      cEn.includes(q) ||
      item.keywords.some((k) => k.includes(q));

    if (countryMatches) {
      const countryTitle =
        item.countryId.toLowerCase() === item.countryEn.toLowerCase()
          ? item.countryId
          : `${item.countryId} (${item.countryEn})`;
      if (!seen.has(countryTitle)) {
        seen.add(countryTitle);
        results.push(countryTitle);
        if (results.length >= limit) return results;
      }
    }

    if (seen.has(item.display)) continue;

    const isMatch =
      countryMatches ||
      display.includes(q) ||
      city.includes(q);

    if (isMatch) {
      seen.add(item.display);
      results.push(item.display);
      if (results.length >= limit) return results;
    }
  }

  return results;
}
